"""Independent rules for reading table columns, normative subjects and amendments."""

import re

TABLE_COLUMN_READING_RULES = """<table_column_reading>
Сначала найди указанную таблицу и строку по номеру И названию поля, затем читай
значение под нужным заголовком колонки. «Формат» (an..19, n..8) и обязательность
(М, С, 3:М) — разные характеристики: не отвечай обязательностью на вопрос о формате.
При изменении формата назови старое → новое значение из нормы о замене; не переноси
изменение на соседнее поле. В норме «X заменить Y» старое = X, новое = Y, не наоборот.
Значение в строке с пометкой о нужном изменении — НОВОЕ; дата исходного акта
в заголовке не делает консолидированную строку старой. Сохраняй условия и исключения
из всех частей целевой строки.
</table_column_reading>"""

NORM_SUBJECT_READING_RULES = """<norm_subject_reading>
Свяжи действие с его субъектом, объектом и условиями в конкретном пункте вопроса.
Не подменяй субъекта соседним участником и не смешивай создание, отмену и автоматическую
отмену. Если спрашивают состав сведений, перечисли все элементы именно соответствующего
пункта, даже при кратком ответе. Различай уникальный номер, присвоенный отправителем,
и номер накладной; дату и время создания, дату накладной и дату отмены. Не заменяй
перечень похожими полями из соседнего пункта или таблицы.
</norm_subject_reading>"""

EDITORIAL_NOTE_READING_RULES = """<editorial_note_reading>
Пометка «абзац введен ...» относится к непосредственно ПРЕДШЕСТВУЮЩЕМУ абзацу,
а не к следующему элементу списка. Для вопроса «кто дополнительно получил право»
найди пометку с нужной датой/номером изменения и назови субъекта именно введённого
абзаца. Пример: «орган А; (абзац введен законом...) орган Б;» — добавлен орган А.
Не выбирай орган Б после скобок. Пометка об исключении не означает предоставления права; дата редакции всего
документа сама по себе не означает, что все перечисленные субъекты добавлены этой датой.
</editorial_note_reading>"""


def evidence_reading_rules(question: str) -> list[str]:
    """Spend prompt tokens on the evidence-reading tasks requested by the user."""
    rules = []
    if re.search(r"таблиц|пол[яею]|формат|колон|столб", question, re.IGNORECASE):
        rules.append(TABLE_COLUMN_READING_RULES)
    if re.search(r"кто|кем|субъект|сведени|удостовер|право", question, re.IGNORECASE):
        rules.append(NORM_SUBJECT_READING_RULES)
    if re.search(r"редакци|дополнительн|введ[её]н|изменен|изменён", question, re.IGNORECASE):
        rules.append(EDITORIAL_NOTE_READING_RULES)
    return rules


def evidence_reading_reminder(question: str) -> str:
    """Short task checklist after long context, without inserting document text."""
    rules = evidence_reading_rules(question)
    if not rules:
        return ""
    reminders = []
    if TABLE_COLUMN_READING_RULES in rules:
        reminders.append(
            "Для вопроса об изменении формата ответь: «В запрошенной редакции формат — Y; "
            "до изменения — X». Y бери из целевой строки с нужным номером поля и пометкой "
            "о запрошенном изменении; X из другой строки того же реквизита с отличающимся форматом. "
            "Не меняй местами X и Y. Для вопроса только о текущем формате назови только Y. "
            "Статус М не является форматом поля."
        )
    if EDITORIAL_NOTE_READING_RULES in rules:
        reminders.append(
            "Если спрашивают, кто добавлен изменением: ответь РОВНО ОДНИМ абзацем из контекста, "
            "который непосредственно предшествует пометке «абзац введен» с нужной датой. "
            "Процитируй только одну ближайшую строку перед скобками и саму пометку. "
            "Не цитируй весь список, не добавляй отдельный вывод или другого субъекта. "
            "Пометка «в ред.» не подходит. "
            "Пометка о введении абзаца относится к тексту ДО скобок. "
            "В последовательности «орган А; (абзац введен...) орган Б;» ответ — орган А."
        )
    if NORM_SUBJECT_READING_RULES in rules:
        reminders.append(
            "Назови субъекта именно указанной нормы. Для состава сведений выпиши ДОСЛОВНО "
            "весь перечень нужного пункта; не сокращай и не перефразируй элементы. "
            "Не путай уникальный номер с номером накладной, дату накладной с датой отмены."
        )
    reminders.append(
        "Если ответ дан по контексту, не добавляй фразу об отсутствии информации. "
        "Заверши ответ ссылкой с числовым номером источника из контекста, например [1]. "
        "Букву N в ссылке не печатай."
    )
    return "\n\nПроверка перед ответом: " + " ".join(reminders)
