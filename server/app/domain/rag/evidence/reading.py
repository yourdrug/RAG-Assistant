"""Independent rules for reading table columns, normative subjects and amendments."""

import re


TABLE_COLUMN_READING_RULES = """<table_column_reading>
Сначала найди указанную таблицу и строку по номеру И названию поля, затем читай
значение под нужным заголовком колонки. «Формат» (an..19, n..8) и обязательность
(\u041c, \u0421, 3:\u041c) — разные характеристики: не отвечай обязательностью на вопрос \u043e формате.
До формулировки табличного ответа извлеки проверяемую пару «название строки → значение»
из одной строки под нужными заголовками, \u0441 её источником. Учитывай страну и другие
уточнения вопроса; сохраняй ведущие нули кодов. Отклоняй пару, если значение взято
из соседней строки или не подтверждено целевой строкой. \u041d\u0435 восстанавливай её по памяти.
При изменении формата назови старое → новое значение из нормы \u043e замене; не переноси
изменение на соседнее поле. \u0412 норме «X заменить Y» старое = X, новое = Y, не наоборот.
Сравнивай один и тот же реквизит в подтверждённых исходной и запрошенной редакциях.
Для поправки сохраняй цепочку: целевая таблица и поле → прежнее значение →
«заменить позицией» → новое значение \u0441\u043e всеми условиями. Два значения без явной
связи замены не доказывают направление изменения. При вопросе \u043e\u0431 обязательности
сравнивай статус, \u0430 не формат. Консолидированная строка \u0441 пометкой «в ред.» —
не независимое доказательство прежнего статуса.
Если \u0435\u0433\u043e значения совпадают или поправка явно затрагивает только другое поле,
допустим ответ «не изменилось». Отсутствие старого значения не доказывает неизменность.
Значение в строке \u0441 пометкой \u043e нужном изменении — \
\u041d\u041e\u0412\u041e\u0415; дата исходного акта
в заголовке не делает консолидированную строку старой. Сохраняй условия и исключения
из всех частей целевой строки.
</table_column_reading>"""

NORM_SUBJECT_READING_RULES = """<norm_subject_reading>
Свяжи действие \u0441 \u0435\u0433\u043e субъектом, объектом и условиями в конкретном пункте вопроса.
\u041d\u0435 подменяй субъекта соседним участником и не смешивай создание, отмену и автоматическую
отмену. Если спрашивают состав сведений, перечисли все элементы именно соответствующего
пункта, даже при кратком ответе. Различай уникальный номер, присвоенный отправителем,
и номер накладной; дату и время создания, дату накладной и дату отмены. \u041d\u0435 заменяй
перечень похожими полями из соседнего пункта или таблицы.
Различай «включённые в перечни» и «\u041d\u0415 включённые в перечни». Отрицание меняет
область действия нормы: режим или срок для одной категории нельзя переносить
на другую. Если нужного подпункта нет, укажи, что режим для запрошенной категории
контекстом не подтверждён; не отвечай режимом противоположной категории.
</norm_subject_reading>"""

PROCEDURE_READING_RULES = """<procedure_reading>
Читай процедуру отдельно по каждому этапу: условие этапа → документ → реквизиты.
Для каждого этапа выпиши собственные строки документа, отправителя, получателя,
стоимостные показатели и основание. \u041d\u0435 переноси реквизиты следующего этапа на
предыдущий. «Последующая доставка» в цели хранения ещё не означает этап отгрузки.
Предложение \u043e реквизитах, связанное в источнике \u0441 условием «При отгрузке», относится
к отгрузке, даже если это отдельный фрагмент. \u0422\u0422\u041d-1 и \u0422\u041d-2 описывай отдельно;
«могут не указываться» не означает запрет и не относится к другому документу.
Ответ организуй по этапам. Для каждого документа сохрани только реквизиты,
подтверждённые именно для него на данном этапе, и ссылку на подтверждающий источник.
</procedure_reading>"""

ENUMERATION_READING_RULES = """<enumeration_reading>
До ответа собери из всех относящихся к вопросу фрагментов перечень категорий, этапов
и случаев вместе \u0441 действием, субъектом, условиями и исключениями каждого.
Перед выдачей сверь ответ \u0441 этим перечнем: все относящиеся к вопросу категории
и условия должны сохраниться, даже при кратком ответе. \u041d\u0435 останавливайся на первых
двух случаях и не объединяй случаи \u0441 разными условиями. Сохраняй различие между
«может» и «должен», \u0430 также «и» и «или». \u041d\u0435 дополняй отсутствующие случаи по памяти;
если контекст неполон, явно обозначь границу подтверждённого ответа.
</enumeration_reading>"""

EDITORIAL_NOTE_READING_RULES = """<editorial_note_reading>
Пометка «абзац введен ...» относится к непосредственно ПРЕДШЕСТВУЮЩЕМУ абзацу,
\u0430 не к следующему элементу списка. Для вопроса «кто дополнительно получил право»
найди пометку \u0441 нужной датой/номером изменения и назови субъекта именно введённого
абзаца. Пример: «орган \u0410; (абзац введен законом...) орган Б;» — добавлен орган \u0410.
\u041d\u0435 выбирай орган Б после скобок. Пометка \u043e\u0431 исключении \
не означает предоставления права; дата редакции всего
документа сама по \u0441\u0435\u0431\u0435 не означает, что все перечисленные субъекты добавлены этой датой.
</editorial_note_reading>"""


def evidence_reading_rules(question: str) -> list[str]:
    """Spend prompt tokens on the evidence-reading tasks requested by the user."""
    rules = []

    if re.search(r"таблиц|пол[яею]|формат|колон|столб|\bк\u043eд\w*", question, re.IGNORECASE):
        rules.append(TABLE_COLUMN_READING_RULES)

    if re.search(
        r"кто|кем|субъект|сведени|удостовер|право|включ[её]н|режим|периодич", question, re.IGNORECASE
    ):
        rules.append(NORM_SUBJECT_READING_RULES)

    if re.search(r"поряд|этап|последующ", question, re.IGNORECASE):
        rules.append(PROCEDURE_READING_RULES)

    if re.search(r"редакци|дополнительн|введ[её]н|изменен|изменён", question, re.IGNORECASE):
        rules.append(EDITORIAL_NOTE_READING_RULES)

    if re.search(
        r"переч|список|состав|сведени|категори|услови|случа|поряд|этап|в зависимости|что входит|что включ",
        question,
        re.IGNORECASE,
    ):
        rules.append(ENUMERATION_READING_RULES)

    return rules


def evidence_reading_reminder(question: str) -> str:
    """Short task checklist after long context, without inserting document text."""
    rules = evidence_reading_rules(question)

    if not rules:
        return ""

    reminders = []

    if TABLE_COLUMN_READING_RULES in rules:
        reminders.append(
            "Для поправки проверь вместе целевое поле, прежнее значение, операцию замены "
            "и новое значение \u0441\u043e всеми условиями. При "
            "вопросе \u043e статусе сравнивай обязательность; "
            "не считай консолидированную строку прежним статусом. "
            "Сначала извлеки из целевой строки пару «название строки → значение» "
            "под нужными заголовками и проверь её источник и уточнения вопроса. "
            "Отклони неподтверждённую пару; значение соседней строки не подходит. "
            "Сохраняй ведущие нули кодов. "
            "Для сравнения формата X и Y должны относиться к одному полю (номер И название) "
            "и подтверждённым исходной и запрошенной редакциям. "
            "При подтверждённом различии ответь: «до изменения — X; после — Y». "
            "Если значения равны или поправка явно меняет только другое поле, ответь «не изменилось» "
            "и назови подтверждённый формат. Если одна редакция не подтверждена, "
            "не выдумывай X и не делай вывод \u043e неизменности из отсутствия данных. "
            "\u041d\u0435 меняй местами X и Y. Для вопроса только \u043e текущем формате назови только Y. "
            "Статус \u041c не является форматом поля."
        )

    if EDITORIAL_NOTE_READING_RULES in rules:
        reminders.append(
            "Если спрашивают, кто добавлен изменением: ответь "
            "\u0420\u041e\u0412\u041d\u041e ОДНИМ абзацем из контекста, "
            "который непосредственно предшествует пометке «абзац введен» \u0441 нужной датой. "
            "Процитируй только одну ближайшую строку перед скобками и саму пометку. "
            "\u041d\u0435 цитируй весь список, не добавляй отдельный вывод или другого субъекта. "
            "Пометка «в ред.» не подходит. "
            "Пометка \u043e введении абзаца относится к тексту ДО скобок. "
            "\u0412 последовательности «орган \u0410; (абзац введен...) орган Б;» ответ — орган \u0410."
        )

    if NORM_SUBJECT_READING_RULES in rules:
        reminders.append(
            "Назови субъекта именно указанной нормы. Для состава сведений выпиши ДОСЛОВНО "
            "весь перечень нужного пункта; не сокращай и не перефразируй элементы. "
            "\u041d\u0435 путай уникальный номер \u0441 номером "
            "накладной, дату накладной \u0441 датой отмены. "
            "Проверь отрицание: норма для \u041d\u0415 включённых в перечни не отвечает на вопрос "
            "\u043e включённых. Если нужной нормы нет, обозначь отсутствие подтверждения."
        )

    if PROCEDURE_READING_RULES in rules:
        reminders.append(
            "Ответь отдельно по каждому этапу в виде «этап → документ → реквизиты». "
            "Внутри этапа отдельно опиши каждый документ. Реквизиты после условия "
            "«При отгрузке» относятся к отгрузке; не переноси их в передачу на хранение. "
            "Для каждой строки, стоимости и основания проверь связь \u0441 этапом и документом. "
            "\u041d\u0435 заполняй неподтверждённые реквизиты догадками."
        )

    if ENUMERATION_READING_RULES in rules:
        reminders.append(
            "Сначала собери все относящиеся к вопросу категории, этапы и случаи из всех "
            "релевантных фрагментов. Перед выдачей сверь \u0441 ними ответ: ни одна категория, "
            "этап, условие или исключение не должны потеряться. Для каждого сохрани действие "
            "и субъекта; не объединяй разные условия и не ограничивайся первыми случаями. "
            "Начни ответ \u0441 названий \u0412\u0421\u0415\u0425 "
            "подтверждённых категорий или этапов, затем кратко "
            "раскрой каждый \u0441 \u0435\u0433\u043e условиями. "
            "Краткость достигается сжатием формулировок, \u0430 не удалением категорий и условий. "
            "\u041d\u0435 добавляй неподтверждённые случаи; при неполном контексте обозначь ограничение."
        )

    reminders.append(
        "Если ответ дан по контексту, не добавляй фразу \u043e\u0431 отсутствии информации. "
        "Заверши ответ ссылкой \u0441 числовым номером источника из контекста, например [1]. "
        "Букву N в ссылке не печатай."
    )
    return "\n\nП\u0440\u043eв\u0435\u0440к\u0430 перед ответом: " + " ".join(reminders)
