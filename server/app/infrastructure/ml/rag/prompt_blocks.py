_REFUSAL_LOCATION = r"в (?:предоставленных |имеющихся )?(?:документах|материалах|контексте)"
_REFUSAL_TOPIC = r"по (?:этому|вашему|данному) вопросу"
_REFUSAL_TAIL = rf"(?: {_REFUSAL_LOCATION})?(?: {_REFUSAL_TOPIC})?(?: {_REFUSAL_LOCATION})?"
_REFUSAL_RE = re.compile(
    r"(?:к сожалению,? )?"
    rf"(?:{_REFUSAL_LOCATION},? )?"
    r"(?:"
    rf"(?:(?:информация|ответ|сведения|данные)(?: {_REFUSAL_TOPIC})? )?"
    r"(?:не найден[аоы]?|не обнаружен[аоы]?|отсутству(?:ет|ют))"
    r"|нет (?:информации|сведений|данных)"
    r"|не удалось найти(?: (?:информацию|ответ|сведения))?"
    r")"
    rf"{_REFUSAL_TAIL}[.!]*"
)
_CITATION_RE = re.compile(r"\s*\[\d+(?:\s*[,;]\s*\d+)*\]")


def is_not_found_answer(answer: str) -> bool:
    """Return True when the whole answer is a refusal, with or without citations.

    A refusal sentence appended to substantive content is not a refusal; see
    ``mark_partial_answer``. Shared by post-processing and answer metrics.
    """
    normalized = " ".join(_CITATION_RE.sub("", answer).casefold().split())
    return _REFUSAL_RE.fullmatch(normalized) is not None
