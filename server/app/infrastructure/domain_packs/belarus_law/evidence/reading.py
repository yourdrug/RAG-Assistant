def selected_reading_rules(question: str) -> list[ReadingRule]:
    return [entry for entry in READING_RULES if entry.trigger.search(question)]


def has_reading_rule(question: str, name: str) -> bool:
    return any(entry.name == name for entry in selected_reading_rules(question))


def evidence_reading_rules(question: str) -> list[str]:
    return [entry.rule for entry in selected_reading_rules(question)]


def evidence_reading_reminder(question: str) -> str:
    selected = sorted(selected_reading_rules(question), key=lambda entry: entry.reminder_order)

    if not selected:
        return ""

    reminders = [entry.reminder for entry in selected]
    reminders.append(
        "Если ответ дан по контексту, не добавляй фразу об отсутствии информации. Заверши "
        "ответ ссылкой с числовым номером источника из контекста, например [1]. Букву N в "
        "ссылке не печатай."
    )
    return "\n\n<answer_check>\nПроверка перед ответом: " + " ".join(reminders) + "\n</answer_check>"
