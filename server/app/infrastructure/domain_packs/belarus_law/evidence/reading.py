"""Independent rules for reading table columns, normative subjects and amendments."""

from dataclasses import dataclass
import re


TABLE_COLUMN_READING_RULES = """<table_column_reading>
Сначала найди указанную таблицу и строку по номеру И названию поля, затем читай
значение под нужным заголовком колонки. «Формат» (an..19, n..8) и обязательность
(М, С, 3:М) — разные характеристики: не отвечай обязательностью на вопрос о формате.
До формулировки табличного ответа извлеки проверяемую пару «название строки → значение»
из одной строки под нужными заголовками, с её источником. Учитывай страну и другие
уточнения вопроса; сохраняй ведущие нули кодов. Отклоняй пару, если значение взято
из соседней строки или не подтверждено целевой строкой. Не восстанавливай её по памяти.
При изменении формата назови старое → новое значение из нормы о замене; не переноси
изменение на соседнее поле. В норме «X заменить Y» старое = X, новое = Y, не наоборот.
Сравнивай один и тот же реквизит в подтверждённых исходной и запрошенной редакциях.
Для поправки сохраняй цепочку: целевая таблица и поле → прежнее значение →
«заменить позицией» → новое значение со всеми условиями. Два значения без явной
связи замены не доказывают направление изменения. При вопросе об обязательности
сравнивай статус, а не формат. Консолидированная строка с пометкой «в ред.» —
не независимое доказательство прежнего статуса.
Если его значения совпадают или поправка явно затрагивает только другое поле,
допустим ответ «не изменилось». Отсутствие старого значения не доказывает неизменность.
Значение в строке с пометкой о нужном изменении — \
НОВОЕ; дата исходного акта
в заголовке не делает консолидированную строку старой. Сохраняй условия и исключения
из всех частей целевой строки.
</table_column_reading>"""

NORM_SUBJECT_READING_RULES = """<norm_subject_reading>
Свяжи действие с его субъектом, объектом и условиями в конкретном пункте вопроса.
Не подменяй субъекта соседним участником и не смешивай создание, отмену и автоматическую
отмену. Если спрашивают состав сведений, перечисли все элементы именно соответствующего
пункта, даже при кратком ответе. Различай уникальный номер, присвоенный отправителем,
и номер накладной; дату и время создания, дату накладной и дату отмены. Не заменяй
перечень похожими полями из соседнего пункта или таблицы.
Различай «включённые в перечни» и «НЕ включённые в перечни». Отрицание меняет
область действия нормы: режим или срок для одной категории нельзя переносить
на другую. Если нужного подпункта нет, укажи, что режим для запрошенной категории
контекстом не подтверждён; не отвечай режимом противоположной категории.
</norm_subject_reading>"""

PROCEDURE_READING_RULES = """<procedure_reading>
Читай процедуру отдельно по каждому этапу: условие этапа → документ → реквизиты.
Для каждого этапа выпиши собственные строки документа, отправителя, получателя,
стоимостные показатели и основание. Не переноси реквизиты следующего этапа на
предыдущий. «Последующая доставка» в цели хранения ещё не означает этап отгрузки.
Предложение о реквизитах, связанное в источнике с условием «При отгрузке», относится
к отгрузке, даже если это отдельный фрагмент. ТТН-1 и ТН-2 описывай отдельно;
«могут не указываться» не означает запрет и не относится к другому документу.
Ответ организуй по этапам. Для каждого документа сохрани только реквизиты,
подтверждённые именно для него на данном этапе, и ссылку на подтверждающий источник.
</procedure_reading>"""

ENUMERATION_READING_RULES = """<enumeration_reading>
До ответа собери из всех относящихся к вопросу фрагментов перечень категорий, этапов
и случаев вместе с действием, субъектом, условиями и исключениями каждого.
Перед выдачей сверь ответ с этим перечнем: все относящиеся к вопросу категории
и условия должны сохраниться, даже при кратком ответе. Не останавливайся на первых
двух случаях и не объединяй случаи с разными условиями. Сохраняй различие между
«может» и «должен», а также «и» и «или». Не дополняй отсутствующие случаи по памяти;
если контекст неполон, явно обозначь границу подтверждённого ответа.
</enumeration_reading>"""

EDITORIAL_NOTE_READING_RULES = """<editorial_note_reading>
Пометка «абзац введен ...» относится к непосредственно ПРЕДШЕСТВУЮЩЕМУ абзацу,
а не к следующему элементу списка. Для вопроса «кто дополнительно получил право»
найди пометку с нужной датой/номером изменения и назови субъекта именно введённого
абзаца. Пример: «орган А; (абзац введен законом...) орган Б;» — добавлен орган А.
Не выбирай орган Б после скобок. Пометка об исключении \
не означает предоставления права; дата редакции всего
документа сама по себе не означает, что все перечисленные субъекты добавлены этой датой.
</editorial_note_reading>"""

CONDITIONAL_WORDING_READING_RULES = """<conditional_wording_reading>
Если спрашивают формулировку нормы, приведи её полностью до конца пункта, а не только
первое предложение. Норма вида «при наличии X — A; при отсутствии X — B» состоит из
двух ветвей: назови обе, с их действием, реквизитом, номером поля и указываемым текстом.
Ветвь «при отсутствии» может стоять в соседнем фрагменте того же акта; относи её
к тому же условию X. Не выводи ветвь, которой нет в контексте.
</conditional_wording_reading>"""


AMENDMENT_SUBJECT_READING_RULES = """<amendment_subject_reading>
Вопрос «изменил ли акт X норму Y» решай по двум опорам из контекста: (1) предмет
изменяющего акта — какие пункты, таблицы и поля он меняет, по его собственному тексту;
(2) норма, которая устанавливает Y, — её акт, пункт или подпункт и содержание.
Если изменяющий акт меняет только другие элементы (например, поля структуры накладной),
а Y установлено в другом акте или пункте, который он не затрагивает, ответь «нет»:
назови, что меняет акт, и где и как установлено Y, с номерами подпунктов.
Если в контексте есть только одна опора, назови подтверждённую часть и прямо укажи,
чего не хватает; не выводи неизменность из одного отсутствия данных.
</amendment_subject_reading>"""


@dataclass(frozen=True)
class ReadingRule:
    name: str
    trigger: re.Pattern[str]
    rule: str
    reminder: str
    reminder_order: int


