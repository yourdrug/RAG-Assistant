def build_nda(path: Path) -> None:
    sizes = {"title": 15, "heading": 13, "text": 10}
    margin, width, height = 60, 475, 842

    with fitz.Document() as pdf:
        page = pdf.new_page()
        y = margin

        for kind, text in NDA_BODY:
            if kind == "break":
                page = pdf.new_page()
                y = margin
                continue

            size = sizes[kind]
            font = BOLD_FONT if kind != "text" else FONT
            rect = fitz.Rect(margin, y, margin + width, height - margin)
            left = page.insert_textbox(
                rect, text, fontsize=size, fontname="B" if kind != "text" else "R", fontfile=str(font)
            )
            used = rect.height - left
            y += used + size * 0.8

        pdf.save(path)


