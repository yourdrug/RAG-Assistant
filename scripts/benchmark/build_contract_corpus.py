def add_multilevel_numbering(document: docx.document.Document) -> None:
    """Register a Word list whose levels render as 1., 1.1., 1.1.1."""
    root = document.part.numbering_part.element
    abstract = OxmlElement("w:abstractNum")
    abstract.set(qn("w:abstractNumId"), NUM_ID)

    for level, text in enumerate(["%1.", "%1.%2.", "%1.%2.%3."]):
        definition = OxmlElement("w:lvl")
        definition.set(qn("w:ilvl"), str(level))

        for tag, value in [("w:start", "1"), ("w:numFmt", "decimal"), ("w:lvlText", text)]:
            element = OxmlElement(tag)
            element.set(qn("w:val"), value)
            definition.append(element)

        abstract.append(definition)

    root.insert(0, abstract)
    num = OxmlElement("w:num")
    num.set(qn("w:numId"), NUM_ID)
    reference = OxmlElement("w:abstractNumId")
    reference.set(qn("w:val"), NUM_ID)
    num.append(reference)
    root.append(num)


def number_paragraph(paragraph: Paragraph, level: int) -> None:
    properties = OxmlElement("w:numPr")

    for name, value in [("ilvl", str(level)), ("numId", NUM_ID)]:
        element = OxmlElement(f"w:{name}")
        element.set(qn("w:val"), value)
        properties.append(element)

    paragraph._p.get_or_add_pPr().append(properties)  # noqa: SLF001 - python-docx has no numbering API


def bold_paragraph(document: docx.document.Document, text: str) -> Paragraph:
    paragraph = document.add_paragraph()
    paragraph.add_run(text).bold = True
    return paragraph


def add_table(document: docx.document.Document, rows: list[tuple[str, ...]]) -> None:
    table = document.add_table(rows=len(rows), cols=len(rows[0]))

    for row, values in zip(table.rows, rows, strict=True):
        for cell, value in zip(row.cells, values, strict=True):
            cell.text = value


